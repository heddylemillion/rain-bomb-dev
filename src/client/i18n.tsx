interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: PropsWithChildren): React.ReactNode {
  const [language, setLanguage] = useState<Language>(() => {
    const storedLanguage = readStorage('rain-burst-language');
    return storedLanguage === 'en' ? 'en' : 'th';
  });

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage: (nextLanguage) => {
        writeStorage('rain-burst-language', nextLanguage);
        setLanguage(nextLanguage);
      },
      t: (key) => messages[language][key],
    }),
    [language]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useTranslation must be used inside LanguageProvider');
  }
  return context;
}
